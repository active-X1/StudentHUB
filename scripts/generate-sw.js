// Rewrites the precache list inside public/service-worker.js from the files on disk.
// Anything admin-related is excluded: the dashboard module is only served to admin sessions, so precaching it
// would fail for everyone else (and admin code must never sit in a shared cache).  Usage: npm run build:sw
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PUBLIC = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public');
const SW = path.join(PUBLIC, 'service-worker.js');
const walk = (d) => readdirSync(d).flatMap((f) => { const p = path.join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });

export function precacheList() {
  const files = walk(path.join(PUBLIC, 'assets')).map((f) => `/${path.relative(PUBLIC, f).split(path.sep).join('/')}`)
    .filter((u) => !path.basename(u).startsWith('.') && !/admin/i.test(u));
  return ['/', '/index.html', '/login.html', '/register.html', '/forgot-password.html', '/manifest.json', ...files.sort()];
}
export function renderSw(source, list) {
  const block = `/* PRECACHE:START (generated by scripts/generate-sw.js) */\nconst SHELL = [\n  ${list.map((u) => `'${u}'`).join(',\n  ')}\n];\n/* PRECACHE:END */`;
  return source.replace(/\/\* PRECACHE:START[\s\S]*?\/\* PRECACHE:END \*\//, block);
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const src = readFileSync(SW, 'utf8'); writeFileSync(SW, renderSw(src, precacheList()));
  console.log(`service-worker.js precache list updated (${precacheList().length} files)`);
}
